export async function copyPublishAssets({
  sourceRoot = repositoryRoot,
  destinationPackage = packageDirectory,
} = {}) {
  await copyPackageAssets({
    repositoryRoot: sourceRoot,
    packageDirectory: destinationPackage,
    assetPaths: PUBLISH_ASSET_PATHS,
  });
  // Package canonical modules behind checkout bridges without maintaining
  // separate implementations for installed consumers.
  for (const [source, destination] of [
    [
      "packages/scripts/plugins/plugin-native-bun-runtime/engine/ios-app-store-runtime-policy.ts",
      "ios-app-store-runtime-policy.ts",
    ],
    ["packages/scripts/lib/workspaces.ts", "workspaces.ts"],
    ["packages/scripts/lib/cli-numbers.ts", "cli-numbers.ts"],
    [
      "packages/scripts/lib/repository-file-integrity.ts",
      "repository-file-integrity.ts",
    ],
  ]) {
    copyFileSync(
      path.join(sourceRoot, source),
      path.join(destinationPackage, "dist/scripts/lib", destination),
    );
  }
  writeFileSync(
    path.join(destinationPackage, "dist/scripts/lib/workspace-discovery.ts"),
    'export { collectWorkspaceMaps } from "./workspaces.ts";\n',
  );
  emitScriptArtifacts(path.join(destinationPackage, "dist/scripts"));
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  await copyPublishAssets();
}
