/** Native payload admission for already hash- and signer-admitted Android APKs. */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { renderOverlay } from "./stage-launcher-overlay.ts";

const stageScript = fileURLToPath(
  new URL("./stage-android-native.py", import.meta.url),
);
const pinPath = "packages/app/scripts/lib/android-bun-artifacts.lock.json";

/** Read pins from the exact reviewed commit, never from mutable checkout bytes. */
export function elizaNativeAdmission({
  sourceRoot,
  sourceCommit,
  packageName,
  bunTarget = "linux-musl",
}) {
  if (!/^[a-f0-9]{40}$/.test(sourceCommit ?? ""))
    throw new Error("A full reviewed runtime source commit is required");
  if (!/^[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$/.test(packageName ?? ""))
    throw new Error("Runtime package identity is required");
  if (!["linux-musl", "android"].includes(bunTarget))
    throw new Error("Unsupported runtime Bun target");
  const git = (...args) =>
    execFileSync("git", ["-C", sourceRoot, ...args], {
      encoding: "utf8",
      maxBuffer: 1024 * 1024,
    });
  const pin = JSON.parse(git("show", `${sourceCommit}:${pinPath}`));
  const bunPin =
    bunTarget === "android"
      ? pin.targets?.android?.stable
      : pin.channels?.stable;
  if (!bunPin)
    throw new Error("Reviewed source has no selected stable Bun pin");
  return {
    schemaVersion: 1,
    bunTarget,
    bunPin,
    maxRuntimeFiles: 10000,
    maxManifestBytes: 16 * 1024 * 1024,
    source: {
      kind: "aosp-build",
      entry: "META-INF/eliza/aosp-build-provenance.json",
      commit: sourceCommit,
      package: packageName,
      maxBytes: 16 * 1024 * 1024,
    },
  };
}

/** The admission contract is generated by the caller from its trusted source inputs. */
export function stageAndroidNative({
  apk,
  output,
  moduleName,
  target = "stallion",
  admission,
  launcher,
  finalizeSoong = false,
}) {
  if (admission?.schemaVersion !== 1)
    throw new Error("Authenticated runtime admission is required");
  if (launcher) {
    if (launcher.moduleName !== moduleName)
      throw new Error("Native module differs from the admitted launcher");
    const full = renderOverlay(launcher).blueprint;
    const main = renderOverlay({
      ...launcher,
      defaultPermissions: undefined,
      companions: undefined,
    }).blueprint;
    if (!full.startsWith(main))
      throw new Error("Cannot separate the admitted launcher module");
    admission = {
      ...admission,
      launcherBlueprint: full,
      remainingBlueprint: full.slice(main.length),
    };
  }
  const temporary = fs.mkdtempSync(
    path.join(os.tmpdir(), "android-native-admission-"),
  );
  try {
    const contract = path.join(temporary, "admission.json");
    fs.writeFileSync(contract, JSON.stringify(admission), { mode: 0o600 });
    return JSON.parse(
      execFileSync(
        "python3",
        [
          stageScript,
          "--apk",
          path.resolve(apk),
          "--output",
          path.resolve(output),
          "--module",
          moduleName,
          "--target",
          target,
          "--admission",
          contract,
          ...(finalizeSoong ? ["--finalize-soong"] : []),
        ],
        { encoding: "utf8", maxBuffer: 4 * 1024 * 1024 },
      ),
    );
  } finally {
    fs.rmSync(temporary, { recursive: true, force: true });
  }
}

/** Convert already admitted native staging after product composition. */
export function finalizeAndroidNative(options) {
  return stageAndroidNative({ ...options, finalizeSoong: true });
}
