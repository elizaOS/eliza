/**
 * AOSP image capability declaration shared by every brand's image.
 *
 * Image-only native surfaces (Phone, Contacts and SMS in the native messages
 * plugin) answer only when the host is installed from a system partition AND
 * the image declares the host's versioned system feature
 * `<launcher package>.aosp_image` (SmsTelephonyConfiguration.imageFeature).
 * Only an image product can put the feature in the product partition; a
 * sideloaded or standalone install never sees it. This writes that feature as a
 * product permissions file next to the staged launcher module. It is staging
 * output: only a boot of the built image shows Android reporting the feature.
 */
import fs from "node:fs";
import path from "node:path";

/** Hosts check the feature with this minimum version. */
export const IMAGE_FEATURE_VERSION = 1;
const packageName = /^[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+$/;

export function imageFeatureName(appId) {
  if (!packageName.test(appId ?? ""))
    throw new Error(`Invalid package ${appId}`);
  return `${appId}.aosp_image`;
}

export function renderImageCapability(appId) {
  const feature = imageFeatureName(appId);
  return {
    [`image-capability/${feature}.xml`]: `<?xml version="1.0" encoding="utf-8"?>
<!-- AOSP image capability for ${appId}. Generated by packages/os/scripts/android/image-capability.mjs.
     Image-only surfaces answer only when this feature is present and the host is installed from a system partition. -->
<permissions>
    <feature name="${feature}" version="${IMAGE_FEATURE_VERSION}" />
</permissions>
`,
    productMakefile: `
# AOSP image capability (packages/os/scripts/android/image-capability.mjs): the system feature ${appId} requires for image-only surfaces.
image_capability_dir := $(patsubst %/,%,$(dir $(lastword $(MAKEFILE_LIST))))/image-capability
PRODUCT_COPY_FILES += $(image_capability_dir)/${feature}.xml:$(TARGET_COPY_OUT_PRODUCT)/etc/permissions/${feature}.xml
`,
  };
}

/** Writes the feature file (never overwriting) and appends its copy rule to the staged product.mk. */
export function writeImageCapability(output, appId) {
  const productMakefile = path.join(output, "product.mk");
  if (!fs.existsSync(productMakefile))
    throw new Error("Image capability requires a staged product.mk");
  const files = renderImageCapability(appId);
  for (const [name, content] of Object.entries(files)) {
    if (name === "productMakefile") continue;
    const file = path.join(output, name);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, { flag: "wx" });
  }
  fs.appendFileSync(productMakefile, files.productMakefile);
  return files;
}

/** The feature a staged product declares for `appId`, or null when it declares none. */
export function stagedImageFeature(output, appId) {
  const feature = imageFeatureName(appId);
  const file = path.join(output, "image-capability", `${feature}.xml`);
  if (!fs.existsSync(file)) return null;
  const declared = fs.readFileSync(file, "utf8");
  const product = fs.readFileSync(path.join(output, "product.mk"), "utf8");
  if (
    !declared.includes(
      `<feature name="${feature}" version="${IMAGE_FEATURE_VERSION}" />`,
    ) ||
    !product.includes(
      `$(image_capability_dir)/${feature}.xml:$(TARGET_COPY_OUT_PRODUCT)/etc/permissions/${feature}.xml`,
    )
  )
    throw new Error(`Staged image capability for ${appId} is not admitted`);
  return { feature, version: IMAGE_FEATURE_VERSION };
}
