/**
 * AOSP image capability declaration shared by every brand's image.
 *
 * Image-only native surfaces (Phone, Contacts and SMS in the native messages
 * plugin) answer only when the host is installed from a system partition AND
 * the image declares the host's versioned system feature
 * `<launcher package>.aosp_image` (SmsTelephonyConfiguration.imageFeature).
 * Only an image product can put the feature in the product partition; a
 * sideloaded or standalone install never sees it. This writes that feature as a
 * product permissions file next to the staged launcher module. It is staging
 * output: only a boot of the built image shows Android reporting the feature.
 */
import fs from "node:fs";
import path from "node:path";

/** Hosts check the feature with this minimum version. */
export const IMAGE_FEATURE_VERSION = 1;
const packageName = /^[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+$/;

export function imageFeatureName(appId) {
  if (!packageName.test(appId ?? ""))
    throw new Error(`Invalid package ${appId}`);
  return `${appId}.aosp_image`;
}

export function renderImageCapability(appId) {
  const feature = imageFeatureName(appId);
  return {
    [`image-capability/${feature}.xml`]: `<?xml version="1.0" encoding="utf-8"?>
<!-- AOSP image capability for ${appId}. Generated by packages/os/scripts/android/image-capability.mjs.
     Image-only surfaces answer only when this feature is present and the host is installed from a system partition. -->
<permissions>
    <feature name="${feature}" version="${IMAGE_FEATURE_VERSION}" />
</permissions>
`,
    productMakefile: `
# AOSP image capability (packages/os/scripts/android/image-capability.mjs): the system feature ${appId} requires for image-only surfaces.
image_capability_dir := $(patsubst %/,%,$(dir $(lastword $(MAKEFILE_LIST))))/image-capability
PRODUCT_COPY_FILES += $(image_capability_dir)/${feature}.xml:$(TARGET_COPY_OUT_PRODUCT)/etc/permissions/${feature}.xml
`,
  };
}

/** Writes the feature file (never overwriting) and appends its copy rule to the staged product.mk. */
export function writeImageCapability(output, appId) {
  const productMakefile = path.join(output, "product.mk");
  if (!fs.existsSync(productMakefile))
    throw new Error("Image capability requires a staged product.mk");
  const files = renderImageCapability(appId);
  for (const [name, content] of Object.entries(files)) {
    if (name === "productMakefile") continue;
    const file = path.join(output, name);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, { flag: "wx" });
  }
  fs.appendFileSync(productMakefile, files.productMakefile);
  return files;
}

/** The feature a staged product declares for `appId`, or null when it declares none. */
export function stagedImageFeature(output, appId) {
  const feature = imageFeatureName(appId);
  const file = path.join(output, "image-capability", `${feature}.xml`);
  if (!fs.existsSync(file)) return null;
  const declared = fs.readFileSync(file, "utf8");
  const product = fs.readFileSync(path.join(output, "product.mk"), "utf8");
  if (
    !declared.includes(
      `<feature name="${feature}" version="${IMAGE_FEATURE_VERSION}" />`,
    ) ||
    !product.includes(
      `$(image_capability_dir)/${feature}.xml:$(TARGET_COPY_OUT_PRODUCT)/etc/permissions/${feature}.xml`,
    )
  )
    throw new Error(`Staged image capability for ${appId} is not admitted`);
  return { feature, version: IMAGE_FEATURE_VERSION };
}

/**
 * Hosts whose APK is presigned (and so cannot be rebuilt with an image-only
 * resource) expose a boolean provisioning resource in an `<overlayable>` with a
 * `system|product` policy, default false. The image enables it with this static
 * product-partition runtime resource overlay. The host still admits the image
 * only with a system-partition install of a release, non-test-mocks build, so
 * the overlay alone never turns an image-only surface on.
 *
 * `module`, `overlayable` and `resource` are the host's own installed
 * identifiers; a brand keeps the names its shipped APK already declares.
 */
const resourceName = /^[a-z][a-z0-9_]*$/;
const overlayableName = /^[A-Za-z][A-Za-z0-9_]*$/;

export function renderImageProvisioningOverlay(
  appId,
  {
    module = "ImageProvisioningOverlay",
    overlayable = "ImageProvisioning",
    resource = "aosp_image_capability",
  } = {},
) {
  imageFeatureName(appId);
  // Explicit identifiers must be strings: a JSON null must never render as "null".
  if (typeof module !== "string" || !overlayableName.test(module))
    throw new Error(`Invalid overlay module ${module}`);
  if (typeof overlayable !== "string" || !overlayableName.test(overlayable))
    throw new Error(`Invalid overlayable ${overlayable}`);
  if (typeof resource !== "string" || !resourceName.test(resource))
    throw new Error(`Invalid provisioning resource ${resource}`);
  return {
    "image-capabilities/Android.bp": `runtime_resource_overlay {\n    name: "${module}",\n    product_specific: true,\n    sdk_version: "current",\n}\n`,
    "image-capabilities/AndroidManifest.xml": `<?xml version="1.0" encoding="utf-8"?>\n<manifest xmlns:android="http://schemas.android.com/apk/res/android" package="${appId}.imagecapabilities">\n    <overlay android:targetPackage="${appId}" android:targetName="${overlayable}" android:isStatic="true" android:priority="10" />\n    <application android:hasCode="false" />\n</manifest>\n`,
    "image-capabilities/res/values/capabilities.xml": `<?xml version="1.0" encoding="utf-8"?>\n<resources><bool name="${resource}">true</bool></resources>\n`,
    "image-capabilities/README.md": `# Image provisioning overlay for ${appId}\n\nGenerated by packages/os/scripts/android/image-capability.mjs for production staging only. This static product-partition runtime resource overlay sets \`${resource}\` in the presigned host's \`${overlayable}\` overlayable. The host also requires a system-partition install of a release, non-test-mocks build; HOME role or launcher flavor alone is insufficient. This is staging output, not image boot or device acceptance.\n`,
    productMakefile: `\n# Image provisioning overlay (packages/os/scripts/android/image-capability.mjs) for the presigned ${appId}.\nPRODUCT_PACKAGES += ${module}\n`,
  };
}

/** Writes the overlay (never overwriting) and adds its module to the staged product.mk. */
export function writeImageProvisioningOverlay(output, appId, options) {
  const productMakefile = path.join(output, "product.mk");
  if (!fs.existsSync(productMakefile))
    throw new Error("Image provisioning overlay requires a staged product.mk");
  const files = renderImageProvisioningOverlay(appId, options);
  for (const [name, content] of Object.entries(files)) {
    if (name === "productMakefile") continue;
    const file = path.join(output, name);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, { flag: "wx" });
  }
  fs.appendFileSync(productMakefile, files.productMakefile);
  return files;
}

/**
 * Checks the host's default resource declaration: the provisioning boolean is
 * false and sits in the named overlayable under a `system|product` policy, so
 * only an image partition overlay can set it.
 */
export function assertProvisioningResourceDefault(
  valuesXml,
  {
    overlayable = "ImageProvisioning",
    resource = "aosp_image_capability",
  } = {},
) {
  if (typeof overlayable !== "string" || !overlayableName.test(overlayable))
    throw new Error(`Invalid overlayable ${overlayable}`);
  if (typeof resource !== "string" || !resourceName.test(resource))
    throw new Error(`Invalid provisioning resource ${resource}`);
  if (!new RegExp(`<bool name="${resource}">false</bool>`).test(valuesXml))
    throw new Error(`${resource} must default to false`);
  if (new RegExp(`<bool name="${resource}">(?!false<)`).test(valuesXml))
    throw new Error(`${resource} must be declared only with a false default`);
  const block = new RegExp(
    `<overlayable name="${overlayable}">([\\s\\S]*?)</overlayable>`,
  ).exec(valuesXml)?.[1];
  if (!block) throw new Error(`Overlayable ${overlayable} is not declared`);
  // Every policy that exposes the resource must be system|product; one exposing
  // it to any other overlay (for example a public policy) is refused.
  const item = new RegExp(`<item type="bool" name="${resource}" />`);
  const exposing = [
    ...block.matchAll(/<policy type="([^"]+)">([\s\S]*?)<\/policy>/g),
  ].filter((policy) => item.test(policy[2]));
  if (!exposing.length)
    throw new Error(`${overlayable} does not expose ${resource}`);
  if (exposing.some((policy) => policy[1] !== "system|product"))
    throw new Error(`${overlayable} must allow only system|product overlays`);
  return true;
}
