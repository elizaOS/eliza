#!/usr/bin/env node
/**
 * Regenerates the legacy differential fixture for entity resolution (#24765 /
 * PR #27941 review follow-up). Extracts `packages/core/src/entities.ts` at
 * the pinned merge-base blob via verified git bytes and writes it to
 * `src/__tests__/fixtures/differential-legacy-entities.ts`, rewriting ONLY
 * module-relative import specifiers (the fixture sits two directory levels
 * deeper than the source module); the resolution logic is byte-identical to
 * develop. Run from the repository root after fetching develop:
 *
 *   git fetch <elizaOS remote> +refs/heads/develop:refs/remotes/upstream/develop
 *   node packages/core/src/__tests__/fixtures/generate-differential-fixture.mjs
 *
 * The generator asserts each rewrite lands exactly once and that no stray
 * `./` specifier survives, so a develop-side import reshuffle fails loudly
 * instead of silently producing a broken oracle.
 */

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../../../..");
const outPath = path.join(here, "differential-legacy-entities.ts");

// Pinned provenance: the blob hash of develop's entities.ts at the PR's
// merge base (commit 126807701e). `upstream/develop` moves; regeneration
// from a different revision would silently swap the historical baseline, so
// the generator reads the pinned blob first and verifies the bytes it got
// still hash to it, failing loudly on drift.
const MERGE_BASE_COMMIT = "126807701e";
const PINNED_BLOB = "1bd2754a9515c7278b67c7cd90e9b8581f5a30fa";
const SRC_PATH = "packages/core/src/entities.ts";

let srcBuffer = null;
let pinnedRef = "";
try {
	srcBuffer = execFileSync("git", ["show", PINNED_BLOB], { cwd: repoRoot });
	pinnedRef = PINNED_BLOB;
} catch {
	// Object does not exist locally (shallow clone): fall back to the
	// merge-base commit path, which is still the pinned revision.
	srcBuffer = execFileSync(
		"git",
		["show", `${MERGE_BASE_COMMIT}:${SRC_PATH}`],
		{ cwd: repoRoot },
	);
	pinnedRef = `${MERGE_BASE_COMMIT}:${SRC_PATH}`;
}
// Byte provenance: the extracted source must hash to the pinned git blob.
{
	const { createHash } = await import("node:crypto");
	const digest = createHash("sha1")
		.update(`blob ${srcBuffer.length}\0`)
		.update(srcBuffer)
		.digest("hex");
	if (digest !== PINNED_BLOB) {
		throw new Error(
			`extracted source hashes to ${digest}, expected pinned ${PINNED_BLOB} — the ref moved or the tree changed`,
		);
	}
}
let src = srcBuffer.toString("utf8");

// (old specifier, new specifier) — relative imports only, exact bytes.
const rewrites = [
	['} from "./entity-matches";', '} from "../../entity-matches";'],
	['} from "./types";', '} from "../../types";'],
	[
		'import { memoizeTurnWork } from "./trajectory-context.ts";',
		'import { memoizeTurnWork } from "../../trajectory-context.ts";',
	],
	[
		'import * as utils from "./utils";',
		'import * as utils from "../../utils";',
	],
	[
		'import { stableStringify } from "./utils/deterministic";',
		'import { stableStringify } from "../../utils/deterministic";',
	],
	['import("./roles")', 'import("../../roles")'],
	[
		'import type { RolesWorldMetadata } from "./roles";',
		'import type { RolesWorldMetadata } from "../../roles";',
	],
	[
		'import { logger } from "./logger";',
		'import { logger } from "../../logger";',
	],
];

for (const [from, to] of rewrites) {
	const count = src.split(from).length - 1;
	if (count !== 1) {
		throw new Error(
			`specifier rewrite expected exactly once, found ${count}: ${from}`,
		);
	}
	src = src.replace(from, to);
}

const stray = src.match(/from "\.\/|import\("\.\//g);
if (stray) {
	throw new Error(`stray relative specifiers remain: ${stray.join(", ")}`);
}
if (!src.includes("export async function findEntityByName")) {
	throw new Error("extracted source does not contain findEntityByName");
}

const header = `/**
 * LEGACY differential fixture: packages/core/src/entities.ts exactly as it
 * existed at the PR #27941 merge base — commit ${MERGE_BASE_COMMIT}, blob
 * ${PINNED_BLOB} (git blob sha1). Regeneration verifies the bytes still
 * hash to the pinned blob. Generated by
 * ${path.basename(fileURLToPath(import.meta.url))} from verified git bytes.
 * Only module-relative import specifiers are rewritten (the fixture lives
 * two directory levels deeper); the resolution logic is byte-identical to
 * develop. entities.differential.test.ts runs this and the current
 * implementation over the same generated model-response matrix and asserts
 * the current path never over-rejects a shape the legacy path resolved
 * with consistent evidence (#27941 review follow-up). Do not hand-edit:
 * regenerate instead.
 */
`;

writeFileSync(outPath, header + src);
console.log(
	`wrote ${outPath} from ${pinnedRef} (${src.length} bytes after header)`,
);
