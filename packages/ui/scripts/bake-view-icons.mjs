#!/usr/bin/env node
/**
 * Copies generated launcher view icons into committed package assets and emits
 * a typed URL lookup. Keeping PNG bytes outside JavaScript avoids parsing every
 * icon at startup while `import.meta.url` remains deterministic and offline.
 *
 * Usage: node scripts/bake-view-icons.mjs [srcDir]   (default /tmp/view-icons)
 */
import { execFileSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = process.argv[2] || "/tmp/view-icons";
const out = join(
  here,
  "..",
  "src",
  "components",
  "views",
  "view-icons.generated.ts",
);
const assetDir = join(here, "..", "src", "components", "views", "view-icons");

// Fail closed before the destructive rewrite below: on any machine that has
// not run gen-view-icons.mjs (or passed an explicit srcDir), the source
// directory is absent, and proceeding would delete every committed icon and
// bake an empty VIEW_ICONS map with a zero exit status.
if (!existsSync(srcDir)) {
  console.error(
    `[bake-view-icons] source directory ${srcDir} does not exist; ` +
      "run scripts/gen-view-icons.mjs first (FAL_KEY required) or pass the icon directory as an argument. " +
      "Refusing to delete the committed icons under src/components/views/view-icons.",
  );
  process.exit(1);
}

const files = readdirSync(srcDir)
  .filter((f) => f.endsWith(".png"))
  .sort();

if (files.length === 0) {
  console.error(
    `[bake-view-icons] ${srcDir} contains no .png files; ` +
      "refusing to replace the committed icon set with an empty bake.",
  );
  process.exit(1);
}

rmSync(assetDir, { force: true, recursive: true });
mkdirSync(assetDir, { recursive: true });

const entries = files.map((f) => {
  const id = f.slice(0, -4);
  cpSync(join(srcDir, f), join(assetDir, f));
  return `  ${JSON.stringify(id)}: new URL("./view-icons/${f}", import.meta.url).href,`;
});

const ts = `// AUTO-GENERATED by scripts/bake-view-icons.mjs — do not edit by hand.
// Per-icon package assets keep PNG bytes out of the startup JavaScript graph;
// import.meta.url preserves deterministic offline resolution in every host.
export const VIEW_ICONS: Record<string, string> = {
${entries.join("\n")}
};

/** The packaged icon URL for a view/app id, falling back to the generic default. */
export function viewIconDataUri(id: string): string {
  return VIEW_ICONS[id] ?? VIEW_ICONS.default ?? "";
}
`;

writeFileSync(out, ts);

// Emit Biome-conformant output so the committed file is idempotent across re-bakes.
// Biome format-checks this file, but its preferred style (unquoted keys, wrapped
// long lines) differs from the quoted single-line literal written above, so a raw
// write reintroduces format drift that fails CI until someone hand-fixes it. Format
// the file in place to close that loop. Best-effort: the emitted TS is already valid
// without the pass, so a missing/excluded Biome is not fatal to the bake.
const repoRoot = join(here, "..", "..", "..");
const bunx = process.platform === "win32" ? "bunx.cmd" : "bunx";
try {
  execFileSync(bunx, ["@biomejs/biome", "format", "--write", out], {
    stdio: "ignore",
    cwd: repoRoot,
    shell: false,
  });
} catch {
  // Biome unavailable or excluding this path — the generated TS is still valid.
}

console.log(`packaged ${files.length} icons -> ${assetDir} + ${out}`);
