package ai.eliza.plugins.media;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.ByteBuffer;
import java.nio.charset.CodingErrorAction;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.util.Arrays;
import java.util.Base64;
import java.util.Locale;

/**
 * Exact-byte rules for selected documents and reviewed attachment copies: bounded reads, a content
 * signature that must agree with the declared type and name, opaque copies whose bytes are never
 * interpreted, and the bounded PDF export payload. Pure Java; no Android types.
 */
public final class DocumentBytes {
  /** Largest selected file or reviewed attachment copy. */
  public static final int MAX_BYTES = 5 * 1024 * 1024;
  /** Largest PDF a host exports from generated bytes. */
  public static final int PDF_LIMIT = 8 * 1024 * 1024;
  private DocumentBytes() {}
  /** Lowercase hexadecimal SHA-256 of the exact bytes. */
  public static String sha256(byte[] bytes) throws Exception {
    StringBuilder out = new StringBuilder();
    for (byte b : MessageDigest.getInstance("SHA-256").digest(bytes))
      out.append(String.format(Locale.ROOT, "%02x", b & 255));
    return out.toString();
  }
  /**
   * Accepts PDF, PNG, JPEG, WebP or UTF-8 text only when the name's extension, the declared type
   * and the leading bytes agree. Names are a single path segment of at most 120 characters.
   */
  public static void validate(String name, String mime, byte[] data) throws Exception {
    if (name == null || name.length() > 120 || name.isBlank()
        || name.matches(".*[\\\\/\\p{Cntrl}].*") || data.length > MAX_BYTES)
      throw new IllegalArgumentException("Invalid name or file exceeds 5 MiB");
    boolean ok = false;
    String lower = name.toLowerCase(Locale.ROOT);
    switch (mime == null ? "" : mime) {
      case "application/pdf":
        ok = lower.endsWith(".pdf") && data.length >= 5
            && new String(data, 0, 5, StandardCharsets.US_ASCII).equals("%PDF-");
        break;
      case "image/png":
        ok = lower.endsWith(".png") && data.length >= 8
            && Arrays.equals(
                Arrays.copyOf(data, 8), new byte[] {(byte) 137, 80, 78, 71, 13, 10, 26, 10});
        break;
      case "image/jpeg":
        ok = (lower.endsWith(".jpg") || lower.endsWith(".jpeg")) && data.length >= 3
            && (data[0] & 255) == 255 && (data[1] & 255) == 216 && (data[2] & 255) == 255;
        break;
      case "image/webp":
        ok = lower.endsWith(".webp") && data.length >= 12
            && new String(data, 0, 4, StandardCharsets.US_ASCII).equals("RIFF")
            && new String(data, 8, 4, StandardCharsets.US_ASCII).equals("WEBP");
        break;
      case "text/plain":
        ok = lower.endsWith(".txt")
            && StandardCharsets.UTF_8.newDecoder()
                    .onMalformedInput(CodingErrorAction.REPORT)
                    .decode(ByteBuffer.wrap(data))
                    .toString()
                    .indexOf('\0')
                < 0;
        break;
      default:
        break;
    }
    if (!ok)
      throw new IllegalArgumentException("File MIME/name/content is unsupported");
  }
  /**
   * Opaque byte copy (any type) for saving only: the name is checked, the bytes are never
   * interpreted, previewed or handed to a viewer.
   */
  public static void validateOpaque(String name, byte[] data) {
    if (name == null || name.length() > 120 || name.isBlank() || name.equals(".")
        || name.equals("..") || name.matches(".*[\\\\/\\p{Cntrl}].*") || data.length > MAX_BYTES)
      throw new IllegalArgumentException("Invalid name or file exceeds 5 MiB");
  }
  /** A syntactically valid lowercase type, or {@code application/octet-stream}. */
  public static String opaqueMime(String mime) {
    return mime != null
            && mime.matches("(?i)[a-z0-9][a-z0-9!#$&^_.+-]{0,63}/[a-z0-9][a-z0-9!#$&^_.+-]{0,63}")
        ? mime.toLowerCase(Locale.ROOT)
        : "application/octet-stream";
  }
  /** Reads at most {@link #MAX_BYTES}; a longer stream is refused, never truncated. */
  public static byte[] read(InputStream in) throws IOException {
    if (in == null)
      throw new IOException("Missing source");
    ByteArrayOutputStream out = new ByteArrayOutputStream();
    byte[] block = new byte[16384];
    int n;
    while ((n = in.read(block)) != -1) {
      if (out.size() + n > MAX_BYTES)
        throw new IOException("File exceeds 5 MiB");
      out.write(block, 0, n);
    }
    return out.toByteArray();
  }
  /** Decodes a bounded base64 PDF export payload that starts with the PDF signature. */
  public static byte[] pdf(String encoded) {
    if (encoded == null || encoded.isEmpty() || encoded.length() > 11184812
        || encoded.length() % 4 != 0)
      throw new IllegalArgumentException("Invalid PDF payload");
    byte[] content = Base64.getDecoder().decode(encoded);
    if (content.length < 5 || content.length > PDF_LIMIT || content[0] != '%' || content[1] != 'P'
        || content[2] != 'D' || content[3] != 'F' || content[4] != '-')
      throw new IllegalArgumentException("Invalid PDF payload");
    return content;
  }
}
