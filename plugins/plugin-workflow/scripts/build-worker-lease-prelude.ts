/** Generate the self-contained child prelude; packaged workers cannot import plugin source files. */
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join } from 'node:path';

const services = join(import.meta.dir, '../src/services');
const result = await Bun.build({
  entrypoints: [join(services, 'workflow-worker-lease-entry.ts')],
  target: 'bun',
  format: 'esm',
  minify: true,
});
if (!result.success) throw new Error(result.logs.map(String).join('\n'));
const script = await result.outputs[0].text();
const target = join(services, 'workflow-worker-lease-prelude.ts');
const unformatted = `/** Generated by scripts/build-worker-lease-prelude.ts. */\nexport const workerLeasePrelude = ${JSON.stringify(script)};\n`;
// Resolve the installed repository formatter, never download one. Formatting
// and --check must use the owning package's rules, including quote style.
const require = createRequire(import.meta.url);
const formatted = spawnSync(
  process.execPath,
  [require.resolve('@biomejs/biome/bin/biome'), 'format', '--stdin-file-path', target],
  {
    cwd: join(import.meta.dir, '..'),
    input: unformatted,
    encoding: 'utf8',
    maxBuffer: 8 * 1024 * 1024,
    timeout: 30_000,
  }
);
if (formatted.error) throw formatted.error;
if (formatted.status !== 0)
  throw new Error(`Worker prelude formatting failed: ${formatted.stderr}`);
const generated = formatted.stdout;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated)
    throw new Error('Worker lease prelude is stale; regenerate it');
} else writeFileSync(target, generated);
