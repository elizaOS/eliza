import { execFileSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { pageCommand } from "../../../packages/os/browser/src/page-command.mjs";
import { pageGuidance } from "../../../packages/os/browser/src/page-guidance.mjs";
import { installControlChannel } from "./control-channel.mjs";

// Ship the same command implementation as Chromium. Published native packages
// contain this generated asset and do not need the monorepo at Android build time.
const target = new URL("../resources/control-channel.js", import.meta.url);
const source = execFileSync(
  process.execPath,
  [
    fileURLToPath(import.meta.resolve("@biomejs/biome/bin/biome")),
    "format",
    "--stdin-file-path",
    fileURLToPath(target),
  ],
  {
    input: `// Generated by scripts/build-control-channel.mjs. Do not edit.\n(${installControlChannel.toString()})(${pageCommand.toString()},${pageGuidance.toString()});\n`,
    encoding: "utf8",
  },
);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== source)
    throw new Error(
      "Native control channel is stale; run build-control-channel.mjs",
    );
} else {
  await writeFile(target, source);
}
