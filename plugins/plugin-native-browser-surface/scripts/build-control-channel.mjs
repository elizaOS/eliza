import { readFile, writeFile } from "node:fs/promises";
import { pageCommand } from "../../../packages/os/browser/src/commands.mjs";
import { installControlChannel } from "./control-channel.mjs";

// Ship the same command implementation as Chromium. Published native packages
// contain this generated asset and do not need the monorepo at Android build time.
const target = new URL("../resources/control-channel.js", import.meta.url);
const source = `// Generated by scripts/build-control-channel.mjs. Do not edit.\n(${installControlChannel.toString()})(${pageCommand.toString()});\n`;
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== source)
    throw new Error(
      "Native control channel is stale; run build-control-channel.mjs",
    );
} else {
  await writeFile(target, source);
}
